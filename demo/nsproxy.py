#!/usr/bin/env python3
"""Loopback TCP relay whose outbound connections originate INSIDE a guest netns.

A browser on the demo machine connects to 127.0.0.1:<port> in the host
namespace. Each connection is relayed from inside the named guest network
namespace, so the Portcullis gateway sees (and filters) it exactly as traffic
from that guest. This is demo plumbing, not part of Portcullis: it never
touches the gateway and grants nothing.

Requires root (setns) and Python 3.12+ (os.setns).
"""
import argparse
import os
import socket
import threading

MAX_CONNECTIONS = 64

BLOCKED_PAGE = (
    "<!doctype html><meta charset=utf-8><meta name=viewport content='width=device-width'>"
    "<title>Blocked at the gateway</title>"
    "<body style='font:18px system-ui;max-width:34rem;margin:3rem auto;padding:0 1rem'>"
    "<h1>No route through the gateway</h1>"
    "<p>This guest's connection to <b>{target}</b> did not complete within {timeout:g}s. "
    "The Portcullis guard dropped the packets because this device has no active grant.</p>"
    "<p><small>Message generated by the demo relay inside the guest namespace, "
    "not by Portcullis.</small></p>"
)


def relay(src, dst):
    try:
        while True:
            data = src.recv(65536)
            if not data:
                break
            dst.sendall(data)
    except OSError:
        pass
    finally:
        try:
            dst.shutdown(socket.SHUT_WR)
        except OSError:
            pass


def handle(client, netns_path, target, timeout):
    try:
        # setns applies to this OS thread only; the socket created afterwards
        # belongs to the guest namespace for its whole lifetime.
        fd = os.open(netns_path, os.O_RDONLY | os.O_CLOEXEC)
        try:
            os.setns(fd, os.CLONE_NEWNET)
        finally:
            os.close(fd)
        try:
            upstream = socket.create_connection(target, timeout=timeout)
        except OSError:
            body = BLOCKED_PAGE.format(target="%s:%d" % target, timeout=timeout).encode()
            client.sendall(
                b"HTTP/1.1 504 Gateway Timeout\r\nContent-Type: text/html; charset=utf-8\r\n"
                b"Cache-Control: no-store\r\nConnection: close\r\nContent-Length: "
                + str(len(body)).encode() + b"\r\n\r\n" + body
            )
            return
        upstream.settimeout(None)
        back = threading.Thread(target=relay, args=(upstream, client), daemon=True)
        back.start()
        relay(client, upstream)
        back.join(timeout=60)
        upstream.close()
    finally:
        client.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--netns", required=True, help="network namespace name under /run/netns")
    parser.add_argument("--listen-port", type=int, required=True)
    parser.add_argument("--target-host", required=True)
    parser.add_argument("--target-port", type=int, required=True)
    parser.add_argument("--connect-timeout", type=float, default=3.0)
    parser.add_argument("--ready")
    args = parser.parse_args()
    if "/" in args.netns or args.netns.startswith("."):
        parser.error("invalid namespace name")
    netns_path = "/run/netns/" + args.netns
    if not os.path.exists(netns_path):
        parser.error("namespace does not exist: " + args.netns)
    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind(("127.0.0.1", args.listen_port))
    listener.listen(32)
    if args.ready:
        with open(args.ready, "w", encoding="ascii") as f:
            f.write("ready\n")
    target = (args.target_host, args.target_port)
    slots = threading.BoundedSemaphore(MAX_CONNECTIONS)

    def bounded(client):
        try:
            handle(client, netns_path, target, args.connect_timeout)
        finally:
            slots.release()

    while True:
        client, _ = listener.accept()
        if not slots.acquire(blocking=False):
            client.close()
            continue
        threading.Thread(target=bounded, args=(client,), daemon=True).start()


if __name__ == "__main__":
    main()
